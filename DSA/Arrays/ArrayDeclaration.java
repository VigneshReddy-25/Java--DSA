package DSA.Arrays;

public class ArrayDeclaration {
    public static void main(String[] args) {
        int arr1[];
        int arr2[]=new int[5];
        for(int i=0; i<arr2.length; i++){
            System.out.println(arr2[i]);
        }
        int arr3[]={1,2,3,4,5};
        for(int i=0; i<arr3.length; i++){
            System.out.println(arr3[i]);
        }
    }
}
